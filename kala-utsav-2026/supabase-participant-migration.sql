-- KALA UTSAV 2026: backward-compatible participant and school suggestion migration
-- Run once in Supabase SQL Editor before deploying the updated app.
alter table public.kala_registrations
  add column if not exists participant_details jsonb not null default '[]'::jsonb,
  add column if not exists school_verified boolean not null default false,
  add column if not exists school_source text not null default 'manual';

create table if not exists public.kala_school_suggestions (
  id bigint generated by default as identity primary key,
  block text not null,
  school text not null,
  udise text not null default '',
  source text not null default 'manual',
  verification_status text not null default 'Pending Verification',
  created_at timestamptz not null default now()
);
create unique index if not exists kala_school_suggestions_unique
  on public.kala_school_suggestions (lower(block), lower(school), udise);
alter table public.kala_school_suggestions enable row level security;
