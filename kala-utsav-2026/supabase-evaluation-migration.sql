-- Run once in Supabase SQL Editor before using the Evaluation tab.
create table if not exists public.kala_evaluations (
  id bigint generated by default as identity primary key,
  registration_id text not null references public.kala_registrations(id) on delete cascade,
  judge_name text not null,
  category text not null,
  discipline text not null,
  scores jsonb not null,
  total integer not null check (total between 0 and 100),
  remarks text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (registration_id, judge_name)
);
alter table public.kala_evaluations enable row level security;
-- No public policies: only the Edge Function service role accesses this table.
